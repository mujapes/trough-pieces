#!/usr/bin/env python3
"""Writes ecdsa/mont_asm.h: Montgomery multiplication for 4 and 6 limbs as ARM64 instructions chosen by hand (through this small
generator, so the 4- and 6-limb routines are the same text). No compiler decides anything in them.
    void montK(uint64_t *out, const uint64_t *a, const uint64_t *b, const uint64_t *n, uint64_t inv)
out = a * b / 2^(64K) mod n, for a, b < n and inv = -1/n mod 2^64. The running total t[0..K+1] lives in x5..x12."""
def routine(K):
    t=['x%d'%(5+i) for i in range(K+2)]; L=[]; A=L.append
    A('.hidden mont%d'%K); A('.global mont%d'%K); A('.type mont%d, %%function'%K); A('mont%d:'%K)
    for r in t: A('    mov     %s, xzr'%r)
    for i in range(K):
        A('    ldr     x13, [x2, #%d]            // b[%d]'%(8*i,i)); A('    mov     x16, xzr                  // carry')
        for j in range(K):
            A('    ldr     x14, [x1, #%d]'%(8*j)); A('    mul     x15, x14, x13'); A('    umulh   x14, x14, x13')
            A('    adds    %s, %s, x15'%(t[j],t[j])); A('    adc     x14, x14, xzr'); A('    adds    %s, %s, x16'%(t[j],t[j])); A('    adc     x16, x14, xzr')
        A('    adds    %s, %s, x16'%(t[K],t[K])); A('    adc     %s, xzr, xzr'%t[K+1])
        A('    mul     x13, %s, x4               // the multiple of n that clears the lowest limb'%t[0]); A('    mov     x16, xzr')
        for j in range(K):
            A('    ldr     x14, [x3, #%d]'%(8*j)); A('    mul     x15, x14, x13'); A('    umulh   x14, x14, x13')
            A('    adds    %s, %s, x15'%(t[j],t[j])); A('    adc     x14, x14, xzr'); A('    adds    %s, %s, x16'%(t[j],t[j])); A('    adc     x16, x14, xzr')
        A('    adds    %s, %s, x16'%(t[K],t[K])); A('    adc     %s, %s, xzr'%(t[K+1],t[K+1]))
        for j in range(K+1): A('    mov     %s, %s'%(t[j],t[j+1]))          # drop the cleared limb
        A('    mov     %s, xzr'%t[K+1])
    # t (K limbs + t[K]) minus n; keep the difference unless it went below zero
    for j in range(K):
        A('    ldr     x14, [x3, #%d]'%(8*j)); A('    %s    x15, %s, x14'%('subs' if j==0 else 'sbcs',t[j])); A('    str     x15, [x0, #%d]'%(8*j))
    A('    sbcs    x15, %s, xzr'%t[K]); A('    b.hs    1f                        // no borrow: the difference is the answer')
    for j in range(K): A('    str     %s, [x0, #%d]'%(t[j],8*j))
    A('1:  ret')
    return L
out='/* Generated by tools/mont_asm.py: Montgomery multiplication, instructions chosen by hand. */\n'
for K in (4,6):
    out+='__asm__(".text\\n.balign 4\\n"\n'+''.join('    "%s\\n"\n'%l.split('//')[0].rstrip() for l in routine(K))+');\n'
    out+='void mont%d(uint64_t *out, const uint64_t *a, const uint64_t *b, const uint64_t *n, uint64_t inv) __attribute__((visibility("hidden")));\n'%K
open(__file__.rsplit('/',2)[0]+'/ecdsa/mont_asm.h','w').write(out); print('written',len(routine(4)),len(routine(6)),'instructions')
