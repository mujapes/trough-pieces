#!/usr/bin/env python3
"""Writes ecdsa/curves.h: the constants of the NIST curves P-256 and P-384 as big-endian bytes.
Each value is checked here before it is written: the base point comes from an independent library and must lie on the
curve given by p and b; n must be the order (the library accepts n-1 as a private key and refuses n; (n-1)G must be -G)."""
from cryptography.hazmat.primitives.asymmetric import ec
C={256:(ec.SECP256R1(),
 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffff,
 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551,
 0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604b),
 384:(ec.SECP384R1(),
 0xfffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffeffffffff0000000000000000ffffffff,
 0xffffffffffffffffffffffffffffffffffffffffffffffffc7634d81f4372ddf581a0db248b0a77aecec196accc52973,
 0xb3312fa7e23ee7e4988e056be3f82d19181d9c6efe8141120314088f5013875ac656398d8a2ed19d2a85c8edd3ec2aef)}
out='/* Generated by tools/curve_table.py, which checks every value against an independent library before writing it. */\n'
for bits,(curve,p,n,b) in C.items():
    G=ec.derive_private_key(1,curve).public_key().public_numbers(); gx,gy=G.x,G.y
    assert (gy*gy-(gx**3-3*gx+b))%p==0, 'base point not on curve'
    for k in (2,3,12345678901234567890):
        Q=ec.derive_private_key(k,curve).public_key().public_numbers(); assert (Q.y*Q.y-(Q.x**3-3*Q.x+b))%p==0
    M=ec.derive_private_key(n-1,curve).public_key().public_numbers(); assert M.x==gx and M.y==p-gy, 'n is not the order'
    try: ec.derive_private_key(n,curve); raise SystemExit('n accepted as a key')
    except ValueError: pass
    L=bits//8
    for name,v in (('p',p),('n',n),('b',b),('gx',gx),('gy',gy)):
        out+='static const uint8_t P%d_%s[%d] = {%s};\n'%(bits,name,L,','.join(str(x) for x in v.to_bytes(L,'big')))
open(__file__.rsplit('/',2)[0]+'/ecdsa/curves.h','w').write(out); print('curves.h written; all constants verified')
