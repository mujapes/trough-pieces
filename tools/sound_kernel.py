#!/usr/bin/env python3
"""Writes sound/kernel.h: one side of a Kaiser-windowed sinc, 256 steps per sample over 8 samples, 15-bit.
The table is part of the sound piece's meaning; once written it is fixed data."""
import math
def i0(x):
    s=t=1.0; k=1
    while t>1e-12*s: t*=(x/(2*k))**2; s+=t; k+=1
    return s
STEPS,HALF,BETA,CUT=256,8,8.0,0.94
out=[]
for n in range(STEPS*HALF+1):
    t=n/STEPS; x=math.pi*t*CUT
    s=1.0 if n==0 else math.sin(x)/x
    w=i0(BETA*math.sqrt(max(0.0,1-(t/HALF)**2)))/i0(BETA)
    out.append(int(round(32767*CUT*s*w)))
with open(__file__.rsplit('/',2)[0]+'/sound/kernel.h','w') as f:
    f.write('/* Generated by tools/sound_kernel.py: half of a Kaiser(8) windowed sinc, cutoff 0.94, 256 steps a sample, 8 samples. */\n')
    f.write('static const int16_t kernel[%d] = {\n'%len(out))
    for i in range(0,len(out),16): f.write(' '+','.join(str(v) for v in out[i:i+16])+',\n')
    f.write('};\n')
