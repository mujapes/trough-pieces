// sound, written by hand (ARM64): changes a sound's rate and channels, mixes one sound into another. The meaning is
// sound/intent.md; the recorded checks are the judge. Entries: x0 block (the sound made), x1 numbers (16-bit), x2 how many,
// x3 argument, x4 call table. Calls nothing. Samples are 16-bit, lowest byte first; divisions round downward.
// Through convert and resample: x19 the source's samples, x20 rate in, x21 channels in, x22 rate out, x23 channels out, x24 volume
// (256 is full), x25 frames in the source, x26 frames to make, x27 where they go, x28 the frame being made.
    .text
    .global convert
    .global mix
    .global resample
    .macro  ENTER
    stp     x29, x30, [sp, #-96]!
    stp     x19, x20, [sp, #16]
    stp     x21, x22, [sp, #32]
    stp     x23, x24, [sp, #48]
    stp     x25, x26, [sp, #64]
    stp     x27, x28, [sp, #80]
    .endm
    .macro  LEAVE
    ldp     x19, x20, [sp, #16]
    ldp     x21, x22, [sp, #32]
    ldp     x23, x24, [sp, #48]
    ldp     x25, x26, [sp, #64]
    ldp     x27, x28, [sp, #80]
    ldp     x29, x30, [sp], #96
    ret
    .endm
// FDIV: \q = \a divided by \b (more than zero), rounded downward. Uses x16, and \q is not \a or \b.
    .macro  FDIV q, a, b
    sdiv    \q, \a, \b
    msub    x16, \q, \b, \a
    cmp     x16, #0
    ccmp    \a, #0, #0, ne
    cset    x16, lt
    sub     \q, \q, x16
    .endm
// source_of: the plain block at the handle x9 on the table x4, not the block x0 -> x9, or 0. Uses x10.
source_of:
    cmp     x9, #0
    b.lt    8f
    cmp     x9, #255
    b.gt    8f
    add     x9, x9, #256
    ldr     x9, [x4, x9, lsl #3]
    cbz     x9, 9f
    ldr     w10, [x9]
    cmp     w10, #2
    b.ne    8f
    ldr     x10, [x9, #16]
    cmp     x10, #64
    b.lo    8f
    cmp     x9, x0
    b.eq    8f
    ldr     x10, [x0, #16]
    cmp     x10, #64
    b.hs    9f
8:  mov     x9, #0
9:  ret
// front: the numbers both rate changes share -> x0 1, or 0 if they are not usable
front:
    cmp     x2, #6
    b.lt    8f
    ldrsh   x9, [x1]
    mov     x17, x30
    bl      source_of
    mov     x30, x17
    cbz     x9, 8f
    ldrsh   x20, [x1, #2]
    ldrsh   x21, [x1, #4]
    ldrsh   x22, [x1, #6]
    ldrsh   x23, [x1, #8]
    ldrsh   x24, [x1, #10]
    mov     x10, #7680
    cmp     x20, #1
    b.lt    8f
    cmp     x20, x10
    b.gt    8f
    cmp     x22, #1
    b.lt    8f
    cmp     x22, x10
    b.gt    8f
    sub     x10, x21, #1
    cmp     x10, #1
    b.hi    8f
    sub     x10, x23, #1
    cmp     x10, #1
    b.hi    8f
    cmp     x24, #256
    b.hi    8f
    add     x19, x9, #64
    ldr     x25, [x9, #16]
    sub     x25, x25, #64
    lsr     x25, x25, #1
    udiv    x25, x25, x21
    mul     x26, x25, x22
    udiv    x26, x26, x20
    ldr     x10, [x0, #16]
    sub     x10, x10, #64
    lsr     x10, x10, #1
    udiv    x10, x10, x23
    cmp     x26, x10
    csel    x26, x10, x26, hi
    add     x27, x0, #64
    mov     x0, #1
    ret
8:  mov     x0, #0
    ret
// finish: the frame's values x9 (and x10) across the channels asked for, at the volume, into place
    .macro  FINISH
    cmp     x21, x23
    b.eq    52f
    cmp     x21, #1
    b.ne    51f
    mov     x10, x9                     // one channel into two: the same in both
    b       52f
51: add     x9, x9, x10                 // two into one: their average
    asr     x9, x9, #1
52: mul     x11, x28, x23
    mul     x9, x9, x24
    asr     x9, x9, #8
    strh    w9, [x27, x11, lsl #1]
    cmp     x23, #2
    b.ne    53f
    add     x11, x11, #1
    mul     x10, x10, x24
    asr     x10, x10, #8
    strh    w10, [x27, x11, lsl #1]
53:
    .endm

convert:
    ENTER
    bl      front
    cbz     x0, c_bad
    mov     x28, #0
c_frame:
    cmp     x28, x26
    b.hs    c_done
    mul     x11, x28, x20               // where this frame falls in the source: between frame x12 and the next, x13 parts of rate out along
    udiv    x12, x11, x22
    msub    x13, x12, x22, x11
    add     x14, x12, #1
    cmp     x14, x25
    csel    x14, x14, x12, lo
    sub     x15, x22, x13
    mul     x12, x12, x21
    mul     x14, x14, x21
    lsr     x17, x22, #1
    ldrsh   x0, [x19, x12, lsl #1]
    ldrsh   x1, [x19, x14, lsl #1]
    mul     x0, x0, x15
    madd    x0, x1, x13, x0
    add     x0, x0, x17
    FDIV    x9, x0, x22
    cmp     x21, #2
    b.ne    1f
    add     x12, x12, #1
    add     x14, x14, #1
    ldrsh   x0, [x19, x12, lsl #1]
    ldrsh   x1, [x19, x14, lsl #1]
    mul     x0, x0, x15
    madd    x0, x1, x13, x0
    add     x0, x0, x17
    FDIV    x10, x0, x22
1:  FINISH
    add     x28, x28, #1
    b       c_frame
c_done:
    mul     x0, x26, x23
    b       c_out
c_bad:
    mov     x0, #-1
c_out:
    LEAVE

mix:
    cmp     x2, #4
    b.lt    m_bad
    mov     x17, x30
    ldrsh   x9, [x1]
    bl      source_of
    mov     x30, x17
    cbz     x9, m_bad
    ldrsh   x11, [x1, #2]               // volume
    cmp     x11, #256
    b.hi    m_bad
    ldrsh   x12, [x1, #4]
    ldrsh   x13, [x1, #6]
    tbnz    x12, #63, m_bad
    tbnz    x13, #63, m_bad
    add     x12, x12, x13, lsl #15      // where in the sound made the other one starts
    ldr     x13, [x9, #16]
    sub     x13, x13, #64
    lsr     x13, x13, #1                // samples to add
    ldr     x14, [x0, #16]
    sub     x14, x14, #64
    lsr     x14, x14, #1                // room
    cmp     x12, x14
    b.hs    m_none
    sub     x14, x14, x12
    cmp     x13, x14
    csel    x13, x14, x13, hi
    add     x9, x9, #64
    add     x0, x0, #64
    add     x0, x0, x12, lsl #1
    mov     x15, #0
    mov     x16, #32767
    mov     x17, #-32768
1:  cmp     x15, x13
    b.hs    2f
    ldrsh   x1, [x9, x15, lsl #1]
    mul     x1, x1, x11
    asr     x1, x1, #8
    ldrsh   x2, [x0, x15, lsl #1]
    add     x1, x1, x2
    cmp     x1, x16
    csel    x1, x16, x1, gt
    cmp     x1, x17
    csel    x1, x17, x1, lt
    strh    w1, [x0, x15, lsl #1]
    add     x15, x15, #1
    b       1b
2:  mov     x0, x13
    ret
m_none:
    mov     x0, #0
    ret
m_bad:
    mov     x0, #-1
    ret

// The filtered rate change: each frame made is a weighted sum of the source frames around its position, the weights from the
// table at the end by distance.
resample:
    ENTER
    bl      front
    cbz     x0, r_bad
    cmp     x20, x22
    csel    x29, x20, x22, gt           // the wider of the two rates (x29 is saved and has no other use here)
    mov     x28, #0
r_frame:
    cmp     x28, x26
    b.ge    r_done
    mul     x11, x28, x20               // its position
    lsl     x12, x29, #3
    sub     x0, x11, x12
    FDIV    x13, x0, x22
    add     x13, x13, #1                // the first source frame in reach
    add     x0, x11, x12
    FDIV    x14, x0, x22                // and the last
    mov     x9, #0
    mov     x10, #0
    mov     x15, #0                     // the weights' sum
    adr     x17, r_kernel
r_tap:
    cmp     x13, x14
    b.gt    r_sum
    mul     x0, x13, x22
    subs    x0, x0, x11
    cneg    x0, x0, mi
    lsl     x0, x0, #8
    sdiv    x0, x0, x29
    cmp     x0, #2048
    b.gt    r_next
    ldrsh   x0, [x17, x0, lsl #1]
    cmp     x13, #0
    csel    x1, xzr, x13, lt
    sub     x2, x25, #1
    cmp     x13, x25
    csel    x1, x2, x1, ge
    add     x15, x15, x0
    mul     x1, x1, x21
    ldrsh   x2, [x19, x1, lsl #1]
    madd    x9, x0, x2, x9
    cmp     x21, #2
    b.ne    r_next
    add     x1, x1, #1
    ldrsh   x2, [x19, x1, lsl #1]
    madd    x10, x0, x2, x10
r_next:
    add     x13, x13, #1
    b       r_tap
r_sum:
    cmp     x15, #0
    b.gt    1f
    mov     x9, #0
    mov     x10, #0
    b       2f
1:  lsr     x12, x15, #1
    add     x0, x9, x12
    FDIV    x9, x0, x15
    add     x0, x10, x12
    FDIV    x10, x0, x15
    mov     x12, #32767
    mov     x13, #-32768
    cmp     x9, x12
    csel    x9, x12, x9, gt
    cmp     x9, x13
    csel    x9, x13, x9, lt
    cmp     x10, x12
    csel    x10, x12, x10, gt
    cmp     x10, x13
    csel    x10, x13, x10, lt
2:  FINISH
    add     x28, x28, #1
    b       r_frame
r_done:
    mul     x0, x26, x23
    b       r_out
r_bad:
    mov     x0, #-1
r_out:
    LEAVE
    .balign 4
